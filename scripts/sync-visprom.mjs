/**
 * Pull the latest VisProm web demo from GitHub into public/visprom + public/static.
 * Runs before build (and on demand) so the portfolio stays in sync with UPSaclay-VisProm.
 */
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { execSync } from 'node:child_process';
import { fileURLToPath } from 'node:url';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const REPO_ROOT = path.resolve(__dirname, '..');
const VISPROM_REPO = 'https://github.com/MIA-PS-Vis/UPSaclay-VisProm.git';
const VISPROM_BRANCH = 'main';
const STATE_FILE = path.resolve(REPO_ROOT, 'public/visprom-sync.json');
const MANIFEST_FILE = path.resolve(REPO_ROOT, 'src/data/vispromSync.js');

function readJson(filePath, fallback = null) {
  try {
    return JSON.parse(fs.readFileSync(filePath, 'utf8'));
  } catch {
    return fallback;
  }
}

function resolveLatestCommitFromGit() {
  const output = execSync(`git ls-remote ${JSON.stringify(VISPROM_REPO)} refs/heads/${VISPROM_BRANCH}`, {
    encoding: 'utf8',
    stdio: ['ignore', 'pipe', 'pipe'],
  }).trim();
  const sha = output.split(/\s+/)[0];
  if (!sha) {
    throw new Error(`Could not resolve ${VISPROM_BRANCH} for VisProm repo`);
  }
  return {
    sha,
    shortSha: sha.slice(0, 7),
    message: `UPSaclay-VisProm@${VISPROM_BRANCH}`,
    date: new Date().toISOString(),
  };
}

async function fetchLatestCommit() {
  try {
    const response = await fetch(
      `https://api.github.com/repos/MIA-PS-Vis/UPSaclay-VisProm/commits/${VISPROM_BRANCH}`,
      { headers: { Accept: 'application/vnd.github+json', 'User-Agent': 'portfolio-website-sync' } }
    );
    if (response.ok) {
      const data = await response.json();
      return {
        sha: data.sha,
        shortSha: data.sha.slice(0, 7),
        message: (data.commit?.message || '').split('\n')[0],
        date: data.commit?.committer?.date || new Date().toISOString(),
      };
    }
  } catch {
    /* fall back to git */
  }
  return resolveLatestCommitFromGit();
}

function copyDir(src, dest) {
  fs.mkdirSync(dest, { recursive: true });
  for (const entry of fs.readdirSync(src, { withFileTypes: true })) {
    const from = path.join(src, entry.name);
    const to = path.join(dest, entry.name);
    if (entry.isDirectory()) {
      copyDir(from, to);
    } else if (entry.isFile()) {
      fs.copyFileSync(from, to);
    }
  }
}

function patchVispromIndex(html) {
  return html
    .replace(/href="static\//g, 'href="/static/')
    .replace(/src="static\//g, 'src="/static/');
}

function writeManifest(commit) {
  const payload = {
    repo: VISPROM_REPO,
    branch: VISPROM_BRANCH,
    sha: commit.sha,
    shortSha: commit.shortSha,
    message: commit.message,
    syncedAt: new Date().toISOString(),
    demoUrl: `/visprom/index.html?v=${commit.shortSha}`,
  };

  fs.writeFileSync(STATE_FILE, `${JSON.stringify(payload, null, 2)}\n`, 'utf8');
  fs.writeFileSync(
    MANIFEST_FILE,
    `/** Auto-generated by scripts/sync-visprom.mjs — do not edit by hand */\nexport const vispromSync = ${JSON.stringify(payload, null, 2)};\n`,
    'utf8'
  );
}

function syncFromClone(commit) {
  const tempDir = fs.mkdtempSync(path.join(os.tmpdir(), 'visprom-sync-'));
  try {
    execSync(
      `git clone --depth 1 --branch ${VISPROM_BRANCH} ${JSON.stringify(VISPROM_REPO)} ${JSON.stringify(tempDir)}`,
      { stdio: 'pipe' }
    );

    const indexSrc = path.join(tempDir, 'index.html');
    const staticSrc = path.join(tempDir, 'public');
    const indexDest = path.resolve(REPO_ROOT, 'public/visprom/index.html');
    const staticDest = path.resolve(REPO_ROOT, 'public/static');

    if (!fs.existsSync(indexSrc)) {
      throw new Error('VisProm index.html missing in upstream repo');
    }
    if (!fs.existsSync(staticSrc)) {
      throw new Error('VisProm public/ folder missing in upstream repo');
    }

    fs.mkdirSync(path.dirname(indexDest), { recursive: true });
    const html = patchVispromIndex(fs.readFileSync(indexSrc, 'utf8'));
    fs.writeFileSync(indexDest, html, 'utf8');

    if (fs.existsSync(staticDest)) {
      fs.rmSync(staticDest, { recursive: true, force: true });
    }
    copyDir(staticSrc, staticDest);

    const coverSrc = path.join(tempDir, 'covervisprom.png');
    const coverDest = path.resolve(REPO_ROOT, 'public/images/visprom-cover.png');
    if (fs.existsSync(coverSrc)) {
      fs.mkdirSync(path.dirname(coverDest), { recursive: true });
      fs.copyFileSync(coverSrc, coverDest);
    }

    writeManifest(commit);
    console.log(`[sync-visprom] Synced ${commit.shortSha} — ${commit.message}`);
  } finally {
    fs.rmSync(tempDir, { recursive: true, force: true });
  }
}

export async function syncVisprom({ force = false } = {}) {
  const commit = await fetchLatestCommit();
  const state = readJson(STATE_FILE);

  if (!force && state?.sha === commit.sha) {
    console.log(`[sync-visprom] Already on latest (${commit.shortSha})`);
    return state;
  }

  syncFromClone(commit);
  return readJson(STATE_FILE);
}

const isMain = process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url);
if (isMain) {
  const force = process.argv.includes('--force');
  syncVisprom({ force }).catch((error) => {
    console.error(`[sync-visprom] ${error.message || error}`);
    process.exitCode = 1;
  });
}
